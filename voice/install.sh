#!/usr/bin/env bash
# GlobaleSIM Voice — call server installer (Asterisk + DIDLogic) for Ubuntu 24.04
# Safe to run again: it rewrites the config with the answers you give.
# Usage:  bash install.sh
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "Run as root"; exit 1; }
say(){ printf '\n\033[1;33m== %s ==\033[0m\n' "$*"; }
CONF=/etc/globalesim-voice.conf
DL_SERVER=""; DL_USER=""; DL_PASS=""; DID=""; E911=""; TEST_PASS=""
[ -f "$CONF" ] && . "$CONF"

say "1/6 Installing Asterisk, firewall and fail2ban (takes 2-4 minutes)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq asterisk asterisk-core-sounds-en-gsm fail2ban ufw curl openssl >/dev/null
PUBIP=${PUBIP:-$(curl -fsS4 ifconfig.me || curl -fsS4 api.ipify.org || true)}
[ -n "$PUBIP" ] || { echo "Could not detect the public IP. Run: PUBIP=x.x.x.x bash install.sh"; exit 1; }
echo "Public IP: $PUBIP"

say "2/6 DIDLogic details (from your DIDLogic portal → SIP accounts)"
echo "Press Enter to keep the value in [brackets]. Leave the username empty to set DIDLogic up later."
read -rp "DIDLogic SIP server [${DL_SERVER:-sip.nyc.didlogic.net}]: " x; DL_SERVER=${x:-${DL_SERVER:-sip.nyc.didlogic.net}}
read -rp "DIDLogic SIP username [${DL_USER:-}]: " x; DL_USER=${x:-${DL_USER:-}}
if [ -n "$DL_USER" ]; then
  read -rsp "DIDLogic SIP password (hidden, Enter = keep current): " x; echo; DL_PASS=${x:-${DL_PASS:-}}
  [ -n "$DL_PASS" ] || { echo "A password is required"; exit 1; }
fi
read -rp "Your DIDLogic phone number, digits only with country code, e.g. 12145550123 [${DID:-}]: " x; DID=${x:-${DID:-}}
DID=$(echo "$DID" | tr -cd '0-9')
read -rp "Is 911 (E911 with your address) enabled on that number at DIDLogic? y/N [${E911:-n}]: " x; E911=${x:-${E911:-n}}
TEST_PASS=${TEST_PASS:-$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 20)}

umask 077
cat > "$CONF" <<EOF
DL_SERVER='$DL_SERVER'
DL_USER='$DL_USER'
DL_PASS='$DL_PASS'
DID='$DID'
E911='$E911'
TEST_PASS='$TEST_PASS'
EOF
chmod 600 "$CONF"

say "3/6 Writing Asterisk configuration"
cd /etc/asterisk
[ -d /etc/asterisk/original ] || { mkdir original; cp -a pjsip.conf extensions.conf rtp.conf logger.conf original/ 2>/dev/null || true; }

cat > rtp.conf <<EOF
[general]
rtpstart=10000
rtpend=20000
EOF

cat > logger.conf <<EOF
[general]
dateformat=%F %T
[logfiles]
console => notice,warning,error
messages => notice,warning,error
security => security
EOF

{
cat <<EOF
; ===== GlobaleSIM Voice — generated by install.sh =====
[global]
type=global
user_agent=GlobaleSIM Voice
endpoint_identifier_order=ip,username

[transport-udp]
type=transport
protocol=udp
bind=0.0.0.0:5060
external_media_address=$PUBIP
external_signaling_address=$PUBIP
local_net=10.0.0.0/8
local_net=172.16.0.0/12
local_net=192.168.0.0/16

[transport-tcp]
type=transport
protocol=tcp
bind=0.0.0.0:5060
external_media_address=$PUBIP
external_signaling_address=$PUBIP
local_net=10.0.0.0/8
local_net=172.16.0.0/12
local_net=192.168.0.0/16

; ---- Test phone (Zoiper/Linphone) — later each app customer gets one of these ----
[1001]
type=endpoint
transport=transport-udp
context=from-app
disallow=all
allow=ulaw,alaw,g722,gsm
auth=1001-auth
aors=1001
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
dtmf_mode=rfc4733
callerid=GlobaleSIM <${DID:-0}>

[1001-auth]
type=auth
auth_type=userpass
username=1001
password=$TEST_PASS

[1001]
type=aor
max_contacts=3
remove_existing=yes
qualify_frequency=30
EOF
if [ -n "$DL_USER" ]; then cat <<EOF

; ---- DIDLogic trunk ----
[didlogic-auth]
type=auth
auth_type=userpass
username=$DL_USER
password=$DL_PASS

[didlogic-reg]
type=registration
transport=transport-udp
outbound_auth=didlogic-auth
server_uri=sip:$DL_SERVER
client_uri=sip:$DL_USER@$DL_SERVER
contact_user=$DL_USER
retry_interval=60
forbidden_retry_interval=600
expiration=300
line=yes
endpoint=didlogic

[didlogic]
type=endpoint
transport=transport-udp
context=from-didlogic
disallow=all
allow=ulaw,alaw
outbound_auth=didlogic-auth
aors=didlogic
from_user=$DL_USER
from_domain=$DL_SERVER
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
dtmf_mode=rfc4733

[didlogic]
type=aor
contact=sip:$DL_SERVER

[didlogic-identify]
type=identify
endpoint=didlogic
EOF
for h in sip.nyc.didlogic.net sip.lax.didlogic.net "$DL_SERVER"; do echo "match=$h"; done | sort -u
fi
} > pjsip.conf

E911_ON=0; case "$E911" in y|Y|yes|YES) E911_ON=1;; esac
cat > extensions.conf <<EOF
; ===== GlobaleSIM Voice dial plan — generated by install.sh =====
[general]
static=yes
writeprotect=yes

[globals]
DID=$DID
E911_ON=$E911_ON

; Calls coming in from DIDLogic to your number -> ring the test phone
[from-didlogic]
exten => _.,1,NoOp(Inbound call to \${EXTEN} from \${CALLERID(num)})
 same => n,Dial(PJSIP/1001,30)
 same => n,Playback(vm-nobodyavail)
 same => n,Hangup()

; Calls made from the app/test phone
; For now: USA + Canada only. International stays OFF until we add per-customer credit,
; because open international dialing is how phone servers get robbed (toll fraud).
[from-app]
exten => 911,1,GotoIf(\$[\${E911_ON} = 1]?go)
 same => n,Playback(ss-noservice)
 same => n,Hangup()
 same => n(go),Set(CALLERID(num)=\${DID})
 same => n,Dial(PJSIP/911@didlogic,120)
 same => n,Hangup()
exten => _NXXNXXXXXX,1,Goto(from-app,1\${EXTEN},1)
exten => _+1NXXNXXXXXX,1,Goto(from-app,\${EXTEN:1},1)
exten => _1NXXNXXXXXX,1,GotoIf(\$[\${REGEX("^(900|976)" \${EXTEN:1:3})}]?blocked)
 same => n,Set(CALLERID(num)=\${DID})
 same => n,Set(TIMEOUT(absolute)=7200)
 same => n,Dial(PJSIP/\${EXTEN}@didlogic,60)
 same => n,Hangup()
 same => n(blocked),Playback(ss-noservice)
 same => n,Hangup()
exten => _X.,1,Playback(ss-noservice)
 same => n,Hangup()
EOF
# switch off modules we don't use (and that log errors on Ubuntu)
for m in res_config_ldap.so res_geolocation.so res_phoneprov.so res_pjsip_phoneprov_provider.so chan_iax2.so chan_skinny.so chan_mgcp.so chan_unistim.so; do
  grep -q "^noload => $m" modules.conf || echo "noload => $m" >> modules.conf
done
chown -R asterisk:asterisk /etc/asterisk; chmod 640 /etc/asterisk/pjsip.conf

say "4/6 Firewall: SSH, SIP 5060 and call audio 10000-20000"
ufw allow OpenSSH >/dev/null
ufw allow 5060/udp >/dev/null
ufw allow 5060/tcp >/dev/null
ufw allow 10000:20000/udp >/dev/null
ufw --force enable >/dev/null
ufw status | head -12

say "5/6 fail2ban: block anyone guessing passwords"
mkdir -p /var/log/asterisk; touch /var/log/asterisk/messages /var/log/asterisk/security; chown asterisk:asterisk /var/log/asterisk/*
cat > /etc/fail2ban/jail.d/asterisk.local <<EOF
[asterisk]
enabled  = true
filter   = asterisk
logpath  = /var/log/asterisk/messages
           /var/log/asterisk/security
banaction = iptables-allports
maxretry = 5
findtime = 600
bantime  = 86400
EOF
systemctl enable --now fail2ban >/dev/null 2>&1; systemctl restart fail2ban

say "6/6 Starting Asterisk"
systemctl enable asterisk >/dev/null 2>&1
systemctl restart asterisk
sleep 6
asterisk -rx "logger reload" >/dev/null || true
if [ -n "$DL_USER" ]; then asterisk -rx "pjsip show registrations" | grep -E "didlogic|Registered|Rejected|Unregistered" || true; fi

cat <<EOF

================  DONE  ================
Test phone login (for Zoiper or Linphone on your phone):
   Server / domain : $PUBIP
   Username        : 1001
   Password        : $TEST_PASS
   Transport       : UDP, port 5060
Your number        : ${DID:-not set yet}
DIDLogic           : $( [ -n "$DL_USER" ] && echo "configured ($DL_USER @ $DL_SERVER) — 'Registered' above means it's connected" || echo "NOT set yet — run 'bash install.sh' again after creating the SIP account")
911                : $( [ "$E911_ON" = 1 ] && echo "ON" || echo "OFF (plays 'no service' — turn on E911 at DIDLogic, then rerun)")

Keep this password private. Settings are saved in $CONF (root only).
Check status any time:  asterisk -rx "pjsip show registrations"
=======================================
EOF
